-- 为现有用户补充常用中文提示词。按用户和标题幂等写入，不覆盖用户已有模板。
INSERT INTO adi_prompt (user_id, act, prompt)
SELECT users.id, seeds.act, seeds.prompt
FROM adi_user AS users
CROSS JOIN (VALUES
    ('长文摘要', $prompt$请阅读下面的内容，并按以下结构输出：
1. 一句话结论
2. 3～5 条核心要点
3. 关键数据或事实
4. 可执行的下一步

要求：忠于原文，不补充未经证实的信息；缺失内容请标注“原文未说明”。

待处理内容：
{待处理内容}$prompt$),
    ('文本润色', $prompt$请润色下面的文本。在不改变原意和事实的前提下，修正错别字与语病，减少重复表达，增强逻辑衔接和可读性。默认使用专业、自然、简洁的中文；完成后只输出润色后的正文。

原文：
{待润色文本}$prompt$),
    ('中英互译', $prompt$请自动识别下面文本的语言：中文翻译成自然、准确的英文，英文翻译成通顺、地道的中文。保留原有段落、列表、专有名词、数字和 Markdown 格式，只输出译文。

原文：
{待翻译文本}$prompt$),
    ('会议纪要整理', $prompt$请将下面的会议记录整理成结构化纪要，包含：会议主题、关键讨论、明确决策、行动项（负责人、截止时间、交付物）以及待确认问题。不要推测缺失信息，无法确认的内容标注“待确认”。

会议记录：
{会议记录}$prompt$),
    ('专业邮件撰写', $prompt$请根据以下信息撰写一封专业、简洁、礼貌的邮件。邮件应包含清晰的主题、称呼、背景、核心诉求、期望行动和结尾；避免空泛客套。如果信息不足，请使用方括号标出需要补充的内容。

收件人：{收件人}
邮件目的：{邮件目的}
关键信息：{关键信息}
语气：{正式/友好/坚定}$prompt$),
    ('代码审查与修复', $prompt$请审查下面的代码，重点检查正确性、边界条件、安全性、性能、可维护性和并发风险。先按严重程度列出问题并解释原因，再给出可直接替换的修复代码和必要的测试用例；不要改动与问题无关的行为。

技术栈与上下文：{技术栈与上下文}
代码：
{代码}$prompt$),
    ('复杂概念讲解', $prompt$请用由浅入深的方式讲解“{概念}”。先用一句话给出直观定义，再使用生活化类比说明工作原理，然后介绍关键组成、典型示例、常见误区和实际应用。面向水平为“{初学者/进阶/专业}”的读者，必要时使用表格或步骤列表。$prompt$),
    ('方案头脑风暴', $prompt$围绕“{目标或问题}”提出 8 个彼此差异明显、可执行的方案。每个方案请说明核心思路、适用场景、主要优势、潜在风险、预计投入和第一步行动。最后使用统一标准比较这些方案，并推荐最值得优先验证的 2 个方案。$prompt$),
    ('任务拆解与计划', $prompt$请把“{目标}”拆解为可执行计划。输出目标与成功标准、范围边界、阶段与里程碑、任务清单、优先级、负责人建议、依赖关系、风险及应对措施。请给出今天即可开始的前三步；时间或资源信息不足时明确列出假设。$prompt$)
) AS seeds(act, prompt)
WHERE NOT EXISTS (
    SELECT 1
    FROM adi_prompt AS existing
    WHERE existing.user_id = users.id
      AND existing.act = seeds.act
);
